const {chromium}=require('playwright');
(async()=>{
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',e=>{if(e.type()==='error')errors.push(e.text())});
await page.goto('file://'+process.cwd()+'/gather-updates/index.html',{waitUntil:'load'});
await page.evaluate(()=>{localStorage.clear()});
await page.reload({waitUntil:'load'});
if(await page.locator('#gWizard9').count()!==1)throw Error('Wizard missing: '+errors.join('; '));
await page.evaluate(()=>{document.body.classList.remove('gather-simple');gWizard9.start()});
if(!await page.getByText('How many people?',{exact:false}).count())throw Error('Setup missing');
await page.evaluate(()=>gWizard9.next());
if(!await page.getByText('Pick Myself',{exact:false}).count())throw Error('Mode missing');
await page.evaluate(()=>gWizard9.mode('manual'));
await page.locator('#gWizard9 .recipe img').first().waitFor({state:'visible'});
const photoOk=await page.locator('#gWizard9 .recipe img').first().evaluate(img=>img.complete&&img.naturalWidth>0);
if(!photoOk)throw Error('Recipe photo failed to load');
const before=await page.locator('#gWizard9 .steps').innerText();
let ids=await page.evaluate(()=>recipes().filter(r=>r.status==='keep'&&r.category==='Meal 2').slice(0,1).map(r=>r.id));
if(!ids.length)throw Error('No recipes');
await page.evaluate(id=>gWizard9.pick(id),ids[0]);
const after=await page.locator('#gWizard9 .steps').innerText();
if(before===after)throw Error('Tap failed to advance '+before);
if(errors.length)throw Error('Errors: '+errors.join('; '));
await page.evaluate(()=>gUI.view('settings'));
await page.locator('#gatherTestButton').click();
await page.locator('#gatherTestResult .notice').waitFor({state:'visible',timeout:10000});
const diag=await page.locator('#gatherTestProgress').innerText();
if(!diag.includes('Finished:'))throw Error('Diagnostics did not finish');
if(!await page.locator('#gatherCopyTest').count())throw Error('Diagnostic export button missing');
console.log('GATHER DIAGNOSTICS PASS',diag);
await page.evaluate(()=>{localStorage.removeItem('gather-clean-v1');});
await page.reload({waitUntil:'load'});
if(!await page.locator('#gatherClean select').count())throw Error('Without a current week plan app must start in setup');
console.log('GATHER STARTUP PLAN-FIRST PASS');
await page.evaluate(()=>{document.body.classList.add('gather-simple');gClean.begin()});
if(!await page.locator('#gatherClean select').count())throw Error('Clean planner setup not visible');
await page.evaluate(()=>gClean.next());
await page.evaluate(()=>gClean.mode('manual'));
const cleanBefore=await page.locator('#gatherClean h1').innerText();
await page.locator('#gatherClean .mealRow').first().click();
const cleanAfter=await page.locator('#gatherClean h1').innerText();
if(cleanBefore===cleanAfter)throw Error('Clean meal tap did not advance');
await page.evaluate(()=>gClean.go('home'));
if(!await page.locator('#gatherClean').isVisible())throw Error('Clean home missing');
await page.evaluate(()=>gClean.go('settings'));
if(!await page.locator('#gatherClean #gatherTestButton').isVisible())throw Error('Settings tester missing in clean shell');
await page.evaluate(()=>gClean.go('home'));
if(await page.locator('#gatherClean #gatherTestButton').count())throw Error('Settings overlapped home');
// End-to-end new-user journey using only approved records.
await page.evaluate(()=>{gClean.begin();gClean.value('people','2');gClean.value('days','2');gClean.next();gClean.mode('auto')});
if(!await page.locator('#gatherClean').getByText('Here’s your week.').count())throw Error('Autoplan review missing');
const unapproved=await page.evaluate(()=>{const a=recipes().filter(r=>r.status==='keep');const ids=Object.values(JSON.parse(localStorage.getItem('gather-clean-v1')).choices);return ids.filter(id=>!a.some(r=>r.id===id))});
if(unapproved.length)throw Error('Unapproved recipes in suggested week '+unapproved.join(','));
await page.evaluate(()=>gClean.finish());
if(!await page.locator('#gatherClean').getByText('Today’s meals').count())throw Error('Saved plan did not open current day');
await page.reload({waitUntil:'load'});
if(!await page.locator('#gatherClean').getByText('Today’s meals').count())throw Error('Current week plan did not persist after reload');
await page.evaluate(()=>gClean.go('settings'));
await page.evaluate(()=>gClean.go('home'));
await page.evaluate(()=>gClean.go('settings'));
if(!await page.locator('#gatherClean #gather-check').count())throw Error('Updater missing after repeated Settings visits');
if(!await page.locator('#gatherClean #gatherTestButton').count())throw Error('Diagnostics missing after repeated Settings visits');
const missingImages=await page.evaluate(()=>Object.entries(window.GATHER_MEAL_PHOTOS||{}).filter(([id,src])=>!id||!src.startsWith('data:image/jpeg;base64,')));
if(missingImages.length)throw Error('Unpacked photo data '+missingImages.length);
console.log('GATHER END TO END PASS');
console.log('GATHER CLEAN SHELL PASS');
console.log('GATHER SMOKE PASS',before,'=>',after);
await browser.close();
})().catch(e=>{console.error('GATHER SMOKE FAIL',e);process.exit(1)});
